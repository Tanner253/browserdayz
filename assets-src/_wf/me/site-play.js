// Stolovaya played for real against the local server: go to the reader with the blue card, put it in with F, and see the room
// open, the crate stand in it and the infected come. Says what came of it; pictures site-*.
const g = window.__game, out = {};
localStorage.setItem('zona.guide.hide', '1');
const errors = [];
addEventListener('error', (e) => errors.push(String(e.message).slice(0, 160)));
const say = (text) => g.net.send({ t: 'chat', ch: 'global', text });
await g.join();
for (let k = 0; k < 150 && !g.online; k++) await T.wait(100);
out.online = g.online;
if (!g.online) return JSON.stringify({ ...out, refused: g.net.refused });
if (g.paused) g.unpause();
await T.wait(2500);
T.hour(0.3);
const face = (x, z) => {
  g.player.yaw = Math.atan2(-(x - g.player.pos.x), -(z - g.player.pos.z));
  g.player.pitch = -0.02;
};
say('/tp -2565.4 365.3');
await T.wait(6000);
say('/give card_blue');
await T.wait(1500);
out.at = [g.player.pos.x, g.player.pos.y, g.player.pos.z].map((v) => +v.toFixed(1));
out.card = g.inv.count('card_blue');
face(-2562.6, 365.85);
await T.wait(1200);
out.prompt = g.prompt;
await shot('site-reader');
face(-2564.1, 364.2);
await T.wait(900);
await shot('site-reader-close');
g.input.simulate('KeyF', true);
await T.wait(160);
g.input.simulate('KeyF', false);
await T.wait(500);
out.working = !!g.use;
await T.wait(2600);
out.cardAfter = g.inv.count('card_blue');
out.phase = g.sites.state.get('stolovaya');
out.promptAfter = g.prompt;
out.drops = [...g.drops.values()].map((d) => [d.stash.label ?? '', +d.at.x.toFixed(1), +d.at.y.toFixed(1), +d.at.z.toFixed(1)]);
const doors = g.s.buildings.doors, near = doors.filter((d) => Math.hypot(d.pivot.position.x + 2562.6, d.pivot.position.z - 365.85) < 3);
out.door = near.map((d) => d.open);
face(-2560.3, 365.4);
await T.wait(1200);
await shot('site-door-open');
say('/tp -2561.6 365.6');
await T.wait(2500);
face(-2560, 367);
await T.wait(1000);
await shot('site-room');
out.infected = g.horde.bodies?.size ?? g.horde.list?.length ?? null;
say('/tp -2566 366');
await T.wait(9000);
face(-2570, 365);
out.infected2 = g.horde.bodies?.size ?? g.horde.list?.length ?? null;
await shot('site-wave');
out.errors = errors;
return JSON.stringify(out);
